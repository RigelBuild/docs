package main

import (
	"bytes"
	"encoding/json"
	"log/slog"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/RigelBuild/docs/site/gather/internal/bundle"
)

type gatherFixture struct {
	repoRoot string
	siteRoot string
	source   bundle.FetchedSource
}

func makeGatherFixture(t *testing.T, pages map[string]string, configured []string, mount string) gatherFixture {
	t.Helper()
	base := t.TempDir()
	repoRoot := filepath.Join(base, "repo")
	siteRoot := filepath.Join(repoRoot, "site")
	sourceRoot := filepath.Join(base, "source")
	if err := os.MkdirAll(filepath.Join(repoRoot, "docs", "designs", "demo"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(repoRoot, "docs", "designs", "demo", "record.md"), []byte("# Record\n\n[Other](other.md)\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(repoRoot, "docs", "designs", "demo", "other.md"), []byte("# Other\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(siteRoot, 0o755); err != nil {
		t.Fatal(err)
	}
	configuredSources := make([]map[string]string, 0, len(configured))
	for _, repo := range configured {
		configuredSources = append(configuredSources, map[string]string{"repo": repo, "mount": "/" + mount + "/", "config": "default"})
	}
	configuredJSON, err := json.Marshal(configuredSources)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(siteRoot, "sources.json"), configuredJSON, 0o644); err != nil {
		t.Fatal(err)
	}
	for name, content := range pages {
		file := filepath.Join(sourceRoot, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(file, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return gatherFixture{
		repoRoot: repoRoot,
		siteRoot: siteRoot,
		source: bundle.FetchedSource{
			Source: bundle.Source{Repo: "RigelBuild/tool", Mount: mount, Config: bundle.ConfigDefault},
			Root:   sourceRoot,
			SHA:    strings.Repeat("a", 40),
		},
	}
}

func runGather(t *testing.T, fixture gatherFixture, sources []bundle.FetchedSource) (bundle.Manifest, string, error) {
	t.Helper()
	var logs bytes.Buffer
	logger := slog.New(slog.NewTextHandler(&logs, nil))
	manifest, err := gather(fixture.repoRoot, fixture.siteRoot, sources, logger)
	return manifest, logs.String(), err
}

func TestGatherOverSourceTree(t *testing.T) {
	t.Run("writes bundled pages with editUrl frontmatter and counts them in the manifest", func(t *testing.T) {
		fixture := makeGatherFixture(t, map[string]string{"guide.md": "# Guide\n\nBody.\n", "README.md": "# Tool\n\nIntro.\n"}, []string{"RigelBuild/tool"}, "tool")
		manifest, _, err := runGather(t, fixture, []bundle.FetchedSource{fixture.source})
		if err != nil {
			t.Fatal(err)
		}
		content := filepath.Join(fixture.siteRoot, "src", "content", "docs")
		for file, want := range map[string]string{
			filepath.Join(content, "tool", "guide", "index.md"): "editUrl: \"https://github.com/RigelBuild/tool/edit/main/guide.md\"",
			filepath.Join(content, "tool", "index.md"):          "editUrl: \"https://github.com/RigelBuild/tool/edit/main/README.md\"",
		} {
			written, err := os.ReadFile(file)
			if err != nil || !strings.Contains(string(written), want) {
				t.Fatalf("read %s: %v; content %q", file, err, written)
			}
			if strings.Contains(string(written), "# Guide") {
				t.Fatalf("page retains heading: %s", written)
			}
		}
		wantSource := bundle.ManifestSource{Repo: "RigelBuild/tool", Ref: "main", SHA: strings.Repeat("a", 40), Pages: 2}
		if len(manifest.Sources) != 1 || manifest.Sources[0] != wantSource {
			t.Fatalf("manifest sources = %#v, want %#v", manifest.Sources, wantSource)
		}
		written, err := os.ReadFile(filepath.Join(fixture.siteRoot, "public", "_bundle.json"))
		if err != nil {
			t.Fatal(err)
		}
		var public bundle.Manifest
		if err := json.Unmarshal(written, &public); err != nil || len(public.Sources) != 1 || public.Sources[0] != wantSource {
			t.Fatalf("manifest file = %#v, %v", public, err)
		}
		record, err := os.ReadFile(filepath.Join(content, "designs", "demo", "record.md"))
		if err != nil || !strings.Contains(string(record), "[Other](/designs/demo/other)") {
			t.Fatalf("design link = %q, %v", record, err)
		}
	})
	t.Run("strips source frontmatter and titles from H1 or page_title", func(t *testing.T) {
		fixture := makeGatherFixture(t, map[string]string{
			"guide.md":    "---\n# generated by https://github.com/hashicorp/terraform-plugin-docs\npage_title: \"user Resource\"\n---\n# user Resource\n\nBody text.\n",
			"fallback.md": "---\npage_title: \"Setup Guide\"\n---\n\nBody without a heading.\n",
		}, []string{"RigelBuild/tool"}, "tool")
		if _, _, err := runGather(t, fixture, []bundle.FetchedSource{fixture.source}); err != nil {
			t.Fatal(err)
		}
		content := filepath.Join(fixture.siteRoot, "src", "content", "docs", "tool")
		guide, err := os.ReadFile(filepath.Join(content, "guide", "index.md"))
		if err != nil || !strings.Contains(string(guide), "title: \"user Resource\"") || strings.Contains(string(guide), "generated by") || strings.Contains(string(guide), "page_title") || strings.Count(string(guide), "---") != 2 {
			t.Fatalf("guide = %q, %v", guide, err)
		}
		fallback, err := os.ReadFile(filepath.Join(content, "fallback", "index.md"))
		if err != nil || !strings.Contains(string(fallback), "title: \"Setup Guide\"") || strings.Contains(string(fallback), "page_title") {
			t.Fatalf("fallback = %q, %v", fallback, err)
		}
	})
	t.Run("strips malformed source frontmatter and warns", func(t *testing.T) {
		fixture := makeGatherFixture(t, map[string]string{"guide.md": "---\nlayout: \"\"\ndescription: |-\nUnindented block text\n---\n# Upgrade Guide\n\nBody.\n"}, []string{"RigelBuild/tool"}, "tool")
		_, logs, err := runGather(t, fixture, []bundle.FetchedSource{fixture.source})
		if err != nil {
			t.Fatal(err)
		}
		guide, err := os.ReadFile(filepath.Join(fixture.siteRoot, "src", "content", "docs", "tool", "guide", "index.md"))
		if err != nil || !strings.Contains(string(guide), "title: \"Upgrade Guide\"") || strings.Contains(string(guide), "Unindented block text") || !strings.Contains(logs, "unparsable frontmatter") {
			t.Fatalf("guide = %q, logs %q, err %v", guide, logs, err)
		}
	})
	t.Run("refuses to gather when a configured source was not fetched", func(t *testing.T) {
		fixture := makeGatherFixture(t, map[string]string{"guide.md": "# Guide\n"}, []string{"RigelBuild/tool", "RigelBuild/other"}, "tool")
		_, _, err := runGather(t, fixture, []bundle.FetchedSource{fixture.source})
		if err == nil || err.Error() != "missing fetched source(s): RigelBuild/other" {
			t.Fatalf("gather error = %v", err)
		}
	})
	t.Run("refuses source mounted at designs", func(t *testing.T) {
		fixture := makeGatherFixture(t, map[string]string{"guide.md": "# Guide\n"}, []string{"RigelBuild/tool"}, "designs")
		_, _, err := runGather(t, fixture, []bundle.FetchedSource{fixture.source})
		if err == nil || err.Error() != "source mount may not be designs: RigelBuild/tool" {
			t.Fatalf("gather error = %v", err)
		}
	})
	t.Run("warns when a bundled page links to a missing file", func(t *testing.T) {
		fixture := makeGatherFixture(t, map[string]string{"guide.md": "# Guide\n\n[Missing](absent.md)\n"}, []string{"RigelBuild/tool"}, "tool")
		_, logs, err := runGather(t, fixture, []bundle.FetchedSource{fixture.source})
		if err != nil || !strings.Contains(logs, "gather: broken link RigelBuild/tool/guide.md -> absent.md") {
			t.Fatalf("gather logs %q, error %v", logs, err)
		}
	})
}
